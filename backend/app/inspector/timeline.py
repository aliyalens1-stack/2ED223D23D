class AppendBody(BaseModel):
    jobId: Optional[str] = None
    reportId: Optional[str] = None
    kind: str
    severity: Optional[str] = None
    title: Optional[str] = None
    text: Optional[str] = None
    metadata: Optional[Dict[str, Any]] = None


@router.post("/timeline/append")
async def append_endpoint(body: AppendBody, uid: str = Depends(get_user_id_required)):
    """Manual append (e.g. inspector flags `critical_issue_found`)."""
    evt = await append_event(
        kind=body.kind,
        job_id=body.jobId,
        report_id=body.reportId,
        inspector_id=uid,
        actor_type="inspector",
        actor_id=uid,
        severity=body.severity,
        title=body.title,
        text=body.text,
        metadata=body.metadata,
    )
    if not evt:
        raise HTTPException(500, "timeline write failed")
    return evt


@router.get("/timeline")
async def list_timeline(
    uid: str = Depends(get_user_id_required),
    jobId: Optional[str] = Query(None),
    reportId: Optional[str] = Query(None),
    kinds: Optional[str] = Query(None, description="Comma-separated kinds"),
    limit: int = Query(100, ge=1, le=500),
):
    """List timeline events for the calling inspector."""
    db = get_db()
    q: Dict[str, Any] = {"inspectorId": uid}
    if jobId:
        q["jobId"] = jobId
    if reportId:
        q["reportId"] = reportId
    if kinds:
        ks = [k.strip() for k in kinds.split(",") if k.strip()]
        if ks:
            q["kind"] = {"$in": ks}

    out: List[Dict[str, Any]] = []
    cursor = db.timeline_events.find(q, {"_id": 0}).sort("timestamp", -1).limit(limit)
    async for r in cursor:
        out.append(r)
    return {"events": out, "count": len(out)}


