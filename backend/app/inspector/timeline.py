"""Inspector Timeline Engine — operational event spine (Sprint 2 Step 1).

Single source of truth for every lifecycle action of inspection jobs.
Consumers: inspector home rail, admin live feed, future notifications fan-out,
reputation engine, dispute audit, payout reconciliation.

Canonical event shape:
    {
      "id":          "evt_<kind>_<stableKey>",      # stable, dedup key
      "namespace":   "inspector",                   # future: customer/admin/system
      "kind":        "<canonical-kind>",
      "jobId":       "...",                         # required for inspector ops
      "reportId":    "..." | None,
      "vehicleId":   "..." | None,
      "inspectorId": "..." | None,
      "customerId":  "..." | None,
      "actor": {
        "type":   "inspector|admin|customer|qa|system",
        "id":     "<userId or system>",
        "label":  "Human readable label"
      },
      "title":       "Short title",
      "text":        "Human readable summary",
      "severity":    "info|success|warning|critical",
      "timestamp":   "ISO-8601 UTC",
      "metadata":    { ... }                        # arbitrary payload
    }

Idempotency: each canonical event gets a stable id (see `make_event_id`).
append_event uses upsert on `id` — calling it twice is a no-op.

Realtime mirror: every successful append is mirrored to
`app.system.realtime.record_event` (in-memory deque) so admin live feed
keeps working without any change on the transport layer.
"""
